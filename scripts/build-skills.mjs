// Builds self-contained, agent-agnostic skill folders (Agent Skills SKILL.md format)
// from this repo's single source of truth:
//   portable/src/<skill>/SKILL.md  -> hand-written skill instructions
//   agents/*.md                    -> reference prompts (frontmatter stripped)
//   src/cli.ts                     -> bundled into a dependency-free scripts/reckoning.mjs,
//                                     with zod swapped for src/portable/zod-lite.ts so the
//                                     script stays short and readable (marketplace scans
//                                     reject large vendored or minified code)
//   examples/forge-pulse/*.md      -> sample output
// Output: portable/skills/<skill>/  (committed, so the folders can be listed as-is).
import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const SKILLS = {
  reckon: {
    references: ['synthesizer', 'praise-engine', 'critic-assassin'],
    examples: ['expected-prd.md', 'expected-verdict.md'],
  },
  'spec-red-team': {
    references: ['praise-engine', 'critic-assassin'],
    examples: ['expected-verdict.md'],
  },
  'idea-to-prd': {
    references: ['synthesizer'],
    examples: ['expected-prd.md'],
  },
  'spec-premortem': {
    references: ['critic-assassin'],
    examples: [],
  },
};

function stripFrontmatter(md) {
  return md.replace(/^---\r?\n[\s\S]*?\r?\n---(\r?\n)+/, '');
}

async function bundleCli() {
  const result = await build({
    entryPoints: [join(ROOT, 'src/cli.ts')],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node18',
    write: false,
    minify: false,
    legalComments: 'none',
    alias: { zod: join(ROOT, 'src/portable/zod-lite.ts') },
    banner: {
      js: '#!/usr/bin/env node\n// Generated by scripts/build-skills.mjs from src/cli.ts (github.com/alchemyguy/reckoning). Do not edit.',
    },
  });
  return result.outputFiles[0].text;
}

export async function buildSkills(outDir = join(ROOT, 'portable/skills')) {
  const cli = await bundleCli();
  rmSync(outDir, { recursive: true, force: true });

  for (const [name, { references, examples }] of Object.entries(SKILLS)) {
    const dir = join(outDir, name);
    mkdirSync(join(dir, 'references'), { recursive: true });
    mkdirSync(join(dir, 'scripts'), { recursive: true });
    if (examples.length > 0) mkdirSync(join(dir, 'examples'), { recursive: true });

    copyFileSync(join(ROOT, 'portable/src', name, 'SKILL.md'), join(dir, 'SKILL.md'));
    copyFileSync(join(ROOT, 'LICENSE'), join(dir, 'LICENSE'));
    writeFileSync(join(dir, 'scripts/reckoning.mjs'), cli);
    chmodSync(join(dir, 'scripts/reckoning.mjs'), 0o755);
    for (const ref of references) {
      const md = readFileSync(join(ROOT, 'agents', `${ref}.md`), 'utf8');
      writeFileSync(join(dir, 'references', `${ref}.md`), stripFrontmatter(md));
    }
    for (const ex of examples) {
      copyFileSync(join(ROOT, 'examples/forge-pulse', ex), join(dir, 'examples', ex));
    }
  }
  return outDir;
}

// Marketplace upload format: one zip per skill with a single top-level folder
// holding SKILL.md at its root (no symlinks, no stray OS files).
export function zipSkills(skillsDir = join(ROOT, 'portable/skills'), outDir = join(ROOT, 'portable/dist')) {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  for (const name of Object.keys(SKILLS)) {
    if (!existsSync(join(skillsDir, name, 'SKILL.md'))) throw new Error(`missing ${name}/SKILL.md`);
    execFileSync('zip', ['-qr', join(outDir, `${name}.zip`), name, '-x', '*.DS_Store'], { cwd: skillsDir });
  }
  return outDir;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = await buildSkills();
  console.log(`built ${Object.keys(SKILLS).length} skills -> ${out}`);
  if (process.argv.includes('--zip')) console.log(`zipped -> ${zipSkills(out)}`);
}
